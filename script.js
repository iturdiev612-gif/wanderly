function setLanguage(lang) {
  let d = words[lang] || words.ru;
  document.documentElement.lang = lang === "ja" ? "ja" : lang;
  document.querySelectorAll("[data-word]").forEach((el) => {
    let k = el.dataset.word;
    if (d[k]) el.innerHTML = d[k];
  });
  try {
    localStorage.setItem("wanderly-lang", lang);
  } catch (e) {}
}
document.addEventListener("DOMContentLoaded", () => {
  const select = document.querySelector("#languageSelect");
  let lang = "ru";
  try {
    lang = localStorage.getItem("wanderly-lang") || "ru";
  } catch (e) {}
  if (select) {
    select.value = lang;
    select.addEventListener("change", () => setLanguage(select.value));
  }
  setLanguage(lang);
  const theme = document.querySelector(".theme-toggle");
  let dark = false;
  try {
    dark = localStorage.getItem("wanderly-theme") === "dark";
  } catch (e) {}
  if (dark) document.body.classList.add("dark-mode");
  function icon() {
    if (theme)
      theme.textContent = document.body.classList.contains("dark-mode")
        ? "☀"
        : "☾";
  }
  icon();
  theme?.addEventListener("click", () => {
    document.body.classList.toggle("dark-mode");
    try {
      localStorage.setItem(
        "wanderly-theme",
        document.body.classList.contains("dark-mode") ? "dark" : "light",
      );
    } catch (e) {}
    icon();
  });
  const toggle = document.querySelector(".menu-toggle"),
    nav = document.querySelector(".main-nav");
  toggle?.addEventListener("click", () => {
    let open = nav.classList.toggle("open");
    toggle.setAttribute("aria-expanded", String(open));
  });
  nav
    ?.querySelectorAll("a")
    .forEach((a) =>
      a.addEventListener("click", () => nav.classList.remove("open")),
    );
  const items = document.querySelectorAll(
    ".intro,.country-card,.section-head,.place,.culture-copy,.fact,.closing,.next",
  );
  if (
    "IntersectionObserver" in window &&
    !matchMedia("(prefers-reduced-motion: reduce)").matches
  ) {
    items.forEach((el) => el.classList.add("reveal"));
    let io = new IntersectionObserver(
      (entries) =>
        entries.forEach((e) => {
          if (e.isIntersecting) {
            e.target.classList.add("visible");
            io.unobserve(e.target);
          }
        }),
      { threshold: 0.12 },
    );
    items.forEach((el) => io.observe(el));
  } else items.forEach((el) => el.classList.add("visible"));
  document
    .querySelectorAll("#year")
    .forEach((el) => (el.textContent = new Date().getFullYear()));
});
